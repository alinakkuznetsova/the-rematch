#This file figures out, given a top-down warped image of the board, which of the 64 squares
#have black pieces on them. = how the camera reads my position.

#The detection method is per-square brightness comparison. during setup i capture a baseline
#image of the empty board. then every frame, i compare each square's current brightness to its
#baseline - if it's noticeably darker, there's a black piece sitting on it.

#The key insight is that I measure darkness as a FRACTION of each square's own baseline brightness,
#not against some absolute number. this is what makes "dark piece on dark square" work - a dark
#square has a low baseline, so the piece only needs to be slightly darker to trigger detection.

#This works cleanly because main.py BLANKS the projection (projects pure black) for the frame it
#reads occupancy on - so the camera sees the physical pieces under no projected light, and there's
#no projector bleed to fight. detection is just "is this square darker than the empty board".

#Test from terminal - runs an interactive 2-phase calibration tool:
#    python -m chess_code.occupancy_detector


from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import chess
import cv2
import numpy as np

from chess_code.board_calibration import (
    Calibration, SQUARE_SIZE, WARPED_SIZE
)



#anchor all saved files to the repo root, not to wherever the terminal happens to be.
#__file__ is this file inside chess_code/; .parent = chess_code, .parent.parent = performing-project.
#this means the baseline always saves to performing-project/calibration/ no matter where you launch
PROJECT_ROOT = Path(__file__).resolve().parent.parent

#where the empty-board baseline gets saved (generated by the interactive _interactive_main below)
BASELINE_PATH = PROJECT_ROOT / "calibration" / "empty_board_baseline.npz"

#how much darker a square has to be (as a fraction of its baseline) to count as occupied
#0.15 = at least 15% darker than empty. this is the magic number i had to tune most -
#too low and false positives everywhere (random shadows trigger detection),
#too high and i miss real pieces (especially black-on-dark-square)
DEFAULT_DARKNESS_THRESHOLD = 0.15

#when measuring a square's brightness, ignore the outer few pixels because they contain
#gridlines from the printed board, edge artifacts from the warp, and the shadow of neighbouring pieces
#10px inset on a 100px square means we look at the central 80x80 region
SQUARE_INSET = 10  #pixels



@dataclass
class OccupancyBaseline:
    #stores the per-square average brightness when the board was empty
    #shape (64,) - one float per square, indexed by chess.Square (0-63 in python-chess a1-h8 order)
    square_means: np.ndarray

    def save(self, path: Path = BASELINE_PATH) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        np.savez(path, square_means=self.square_means)

    @classmethod
    def load(cls, path: Path = BASELINE_PATH) -> "OccupancyBaseline":
        if not path.exists():
            raise FileNotFoundError(
                f"No empty-board baseline at {path}. "
                "Run `python -m chess_code.occupancy_detector` first."
            )
        data = np.load(path)
        return cls(square_means=data["square_means"])



def square_pixel_region(square: chess.Square) -> tuple[int, int, int, int]:
    #for a given chess square, return the pixel rectangle (x0, y0, x1, y1) in the warped image
    #that contains its interior (with the inset margin applied to skip gridlines)
    file_idx = chess.square_file(square)   #0-7, a to h
    rank_idx = chess.square_rank(square)   #0-7, 1 to 8
    x = file_idx * SQUARE_SIZE
    #flip the rank because image y-axis points down but chess ranks go up
    y = (7 - rank_idx) * SQUARE_SIZE
    return (x + SQUARE_INSET,
            y + SQUARE_INSET,
            x + SQUARE_SIZE - SQUARE_INSET,
            y + SQUARE_SIZE - SQUARE_INSET)


def measure_square_brightness(warped_gray: np.ndarray,
                              square: chess.Square) -> float:
    #returns the mean greyscale value (0=black, 255=white) of one square's interior
    x0, y0, x1, y1 = square_pixel_region(square)
    region = warped_gray[y0:y1, x0:x1]
    return float(region.mean())



def capture_baseline(warped_frame: np.ndarray) -> OccupancyBaseline:
    #build a per-square baseline from a single frame of the empty board
    #for actual use, call capture_baseline_averaged instead - single frames are too noisy
    gray = cv2.cvtColor(warped_frame, cv2.COLOR_BGR2GRAY)
    means = np.zeros(64, dtype=np.float32)
    for sq in chess.SQUARES:
        means[sq] = measure_square_brightness(gray, sq)
    return OccupancyBaseline(square_means=means)


def capture_baseline_averaged(warped_frames: list[np.ndarray]
                              ) -> OccupancyBaseline:
    #average multiple frames before measuring to smooth out camera sensor noise
    #i average 30 frames in the calibration tool, takes about 1 second of footage
    if not warped_frames:
        raise ValueError("Need at least one frame to capture baseline.")
    avg = np.mean(np.stack([f.astype(np.float32) for f in warped_frames]),
                  axis=0).astype(np.uint8)
    return capture_baseline(avg)



class OccupancyDetector:
    #reads which squares currently have black pieces, given a warped board image
    #
    #usage:
    #    detector = OccupancyDetector(baseline)
    #    # ...when motion_detector says STABLE...
    #    warped = calibration.warp(camera_frame)
    #    occupied = detector.detect(warped)
    #    # occupied is a set of chess.Square values

    def __init__(self,
                 baseline: OccupancyBaseline,
                 darkness_threshold: float = DEFAULT_DARKNESS_THRESHOLD):
        #baseline: the empty-board reading from capture_baseline()
        #darkness_threshold: how much darker (as a fraction) a square must be to count as occupied
        #    0.15 = 15% darker than baseline. tune this in the lab depending on lighting
        self.baseline = baseline
        self.darkness_threshold = darkness_threshold

    def detect(self, warped_frame: np.ndarray) -> set[chess.Square]:
        #returns the set of squares the camera thinks have black pieces on them
        gray = cv2.cvtColor(warped_frame, cv2.COLOR_BGR2GRAY)
        occupied: set[chess.Square] = set()
        for sq in chess.SQUARES:
            current = measure_square_brightness(gray, sq)
            baseline = self.baseline.square_means[sq]
            #measure the brightness drop as a FRACTION of the baseline
            #this is the key trick - it means dark squares (low baseline) need proportionally
            #less darkening to register as occupied. solves the dark-piece-on-dark-square problem
            #max(baseline, 1.0) just prevents divide-by-zero if a square's baseline is somehow 0
            drop = (baseline - current) / max(baseline, 1.0)
            if drop > self.darkness_threshold:
                occupied.add(sq)
        return occupied

    def detect_with_diagnostics(self,
                                warped_frame: np.ndarray
                               ) -> tuple[set[chess.Square], dict]:
        #same as detect() but also returns per-square numbers (baseline brightness, current, drop)
        #i used this when tuning the threshold to see exactly which squares were borderline
        gray = cv2.cvtColor(warped_frame, cv2.COLOR_BGR2GRAY)
        occupied: set[chess.Square] = set()
        diagnostics: dict[chess.Square, dict] = {}
        for sq in chess.SQUARES:
            current = measure_square_brightness(gray, sq)
            baseline = self.baseline.square_means[sq]
            drop = (baseline - current) / max(baseline, 1.0)
            is_occupied = drop > self.darkness_threshold
            if is_occupied:
                occupied.add(sq)
            diagnostics[sq] = {
                "baseline": baseline,
                "current": current,
                "drop_fraction": drop,
                "occupied": is_occupied,
            }
        return occupied, diagnostics



def draw_debug_overlay(warped_frame: np.ndarray,
                       occupied: set[chess.Square]) -> np.ndarray:
    #draws green rectangles on detected-occupied squares + a faint white grid
    #this is purely for the debug window so i can visually verify the detection is right
    display = warped_frame.copy()
    #faint grid lines so i can see the 8x8 structure
    for i in range(9):
        cv2.line(display, (i * SQUARE_SIZE, 0),
                 (i * SQUARE_SIZE, WARPED_SIZE), (80, 80, 80), 1)
        cv2.line(display, (0, i * SQUARE_SIZE),
                 (WARPED_SIZE, i * SQUARE_SIZE), (80, 80, 80), 1)
    #green rectangles + square names on the occupied squares
    for sq in occupied:
        x0, y0, x1, y1 = square_pixel_region(sq)
        #expand out by the inset amount so the highlight covers the whole visible square
        #not just the inset measurement region
        cv2.rectangle(display,
                      (x0 - SQUARE_INSET, y0 - SQUARE_INSET),
                      (x1 + SQUARE_INSET, y1 + SQUARE_INSET),
                      (0, 255, 0), 2)
        sq_name = chess.square_name(sq)
        cv2.putText(display, sq_name,
                    ((x0 + x1) // 2 - 12, (y0 + y1) // 2 + 5),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 1)
    return display



def _interactive_main(camera_index: int = 0):
    #two-phase interactive calibration tool. i run this once in the lab to set up the baseline
    #+ tune the darkness threshold for the actual lighting conditions
    #
    #phase 1 (capture baseline):
    #    empty board shown live. press SPACE to capture baseline (averages 30 frames for robustness)
    #
    #phase 2 (live tuning):
    #    place pieces on the board. system highlights what it detects as occupied.
    #    use +/- to nudge the threshold up/down until detection matches reality
    #
    #keys:
    #    space  -- in phase 1, capture baseline. in phase 2, recapture (useful if lighting changed)
    #    + / -  -- raise/lower the darkness threshold by 0.01
    #    s      -- save baseline (auto-saves on capture; this re-saves)
    #    q      -- quit

    print(f"Loading board calibration from {BASELINE_PATH.parent}...")
    try:
        board_cal = Calibration.load()
    except FileNotFoundError as e:
        print(f"\nERROR: {e}")
        print("Run board_calibration first to set up the board geometry.")
        return

    cap = cv2.VideoCapture(camera_index)
    if not cap.isOpened():
        raise RuntimeError(f"Could not open camera {camera_index}")

    phase = 1
    baseline: Optional[OccupancyBaseline] = None
    detector: Optional[OccupancyDetector] = None
    threshold = DEFAULT_DARKNESS_THRESHOLD

    print("\nPhase 1: empty-board baseline capture")
    print("  Make sure the board is EMPTY (no pieces on it).")
    print("  Press SPACEBAR to capture the baseline.")
    print("  Press 'q' to quit.\n")

    try:
        while True:
            ok, frame = cap.read()
            if not ok:
                print("Camera read failed.")
                break

            warped = board_cal.warp(frame)

            if phase == 1:
                #just show the live empty board view + instructions
                display = warped.copy()
                cv2.putText(display,
                            "Phase 1: EMPTY BOARD -- press SPACE to capture baseline",
                            (10, 30), cv2.FONT_HERSHEY_SIMPLEX,
                            0.6, (0, 255, 255), 2)
            else:
                #phase 2: show live detection with the green overlay + current threshold value
                occupied, _ = detector.detect_with_diagnostics(warped)
                display = draw_debug_overlay(warped, occupied)
                cv2.putText(display,
                            f"Phase 2: threshold={threshold:.2f}  "
                            f"detected={len(occupied)}  "
                            f"[+/-] tune  [space] re-baseline  [q] quit",
                            (10, 30), cv2.FONT_HERSHEY_SIMPLEX,
                            0.5, (255, 255, 255), 1)

            cv2.imshow("occupancy detector", display)
            key = cv2.waitKey(1) & 0xFF

            if key == ord('q'):
                break
            if key == ord(' '):
                #grab 30 frames + average them. takes about 1 second of footage
                #averaging is important - a single frame has too much sensor noise to be reliable
                print("Capturing baseline (30 frames)...")
                frames = []
                for _ in range(30):
                    ok2, f2 = cap.read()
                    if ok2:
                        frames.append(board_cal.warp(f2))
                baseline = capture_baseline_averaged(frames)
                baseline.save()
                detector = OccupancyDetector(baseline, threshold)
                phase = 2
                print(f"Baseline captured and saved to {BASELINE_PATH}.")
                print("Now place pieces on the board. Occupied squares will be highlighted.")
                print("Use +/- to tune the darkness threshold.\n")
            #+/- live threshold tuning. = and _ also work because on most keyboards you don't
            #need to hold shift for them, which is more convenient
            if key == ord('+') or key == ord('='):
                threshold = min(0.5, threshold + 0.01)
                if detector:
                    detector.darkness_threshold = threshold
            if key == ord('-') or key == ord('_'):
                threshold = max(0.01, threshold - 0.01)
                if detector:
                    detector.darkness_threshold = threshold
            if key == ord('s') and baseline is not None:
                baseline.save()
                print(f"Baseline re-saved to {BASELINE_PATH}")

    finally:
        cap.release()
        cv2.destroyAllWindows()


if __name__ == "__main__":
    import sys
    camera_index = 0
    if len(sys.argv) >= 2:
        try:
            camera_index = int(sys.argv[1])
        except ValueError:
            print(f"Camera index must be an integer; got {sys.argv[1]!r}")
            sys.exit(1)
    _interactive_main(camera_index)